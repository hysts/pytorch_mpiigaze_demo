"""Regression tests for the normalization conventions.

The gaze estimation models were trained on labels generated by the dataset
tooling, so the runtime preprocessing must match those conventions exactly.
The reference implementations in this file are written independently of the
package code, following the MPIIGaze dataset normalization and the
`convert_pose` / `convert_gaze` functions in
hysts/pytorch_mpiigaze `tools/preprocess_mpiigaze.py`.
"""

import cv2
import numpy as np
from scipy.spatial.transform import Rotation

from ptgaze.common import Camera
from ptgaze.common.gaze import denormalize_gaze_vector, gaze_angles_to_vector, gaze_vector_to_angles
from ptgaze.head_pose_estimation import HeadPoseNormalizer


def _make_camera(width: int, height: int, focal: float) -> Camera:
    camera_matrix = np.array([[focal, 0.0, width / 2], [0.0, focal, height / 2], [0.0, 0.0, 1.0]])
    return Camera(width=width, height=height, camera_matrix=camera_matrix, dist_coefficients=np.zeros((5, 1)))


def _make_normalizer(focal_norm: float, distance_norm: float, size: tuple[int, int]) -> HeadPoseNormalizer:
    camera = _make_camera(640, 480, 650.0)
    normalized_camera = _make_camera(size[0], size[1], focal_norm)
    return HeadPoseNormalizer(camera, normalized_camera, distance_norm)


def _random_center_and_rotation(rng: np.random.Generator) -> tuple[np.ndarray, Rotation]:
    center = np.array([rng.uniform(-0.15, 0.15), rng.uniform(-0.1, 0.1), rng.uniform(0.4, 0.8)])
    head_pose_rot = Rotation.from_euler("XYZ", rng.uniform(-25, 25, 3), degrees=True)
    return center, head_pose_rot


def _reference_normalizing_rotation(center: np.ndarray, head_rot_mat: np.ndarray) -> np.ndarray:
    # The look-at rotation used by the MPIIGaze dataset normalization
    # (and by OpenGaze normalizer.cpp).
    forward = center / np.linalg.norm(center)
    down = np.cross(forward, head_rot_mat[:, 0])
    down /= np.linalg.norm(down)
    right = np.cross(down, forward)
    right /= np.linalg.norm(right)
    return np.vstack([right, down, forward])


def _reference_normalized_head_pose(center: np.ndarray, head_rot_mat: np.ndarray) -> np.ndarray:
    # convert_pose() from hysts/pytorch_mpiigaze tools/preprocess_mpiigaze.py,
    # which generated the training labels: the dataset stores the rotation
    # vector of R @ hR, and the 2D head pose is derived from its z-column.
    rot = _reference_normalizing_rotation(center, head_rot_mat)
    rotvec, _ = cv2.Rodrigues(rot @ head_rot_mat)
    mat, _ = cv2.Rodrigues(rotvec)
    z_axis = mat[:, 2]
    return np.array([np.arcsin(z_axis[1]), np.arctan2(z_axis[0], z_axis[2])])


def _reference_convert_gaze(vector: np.ndarray) -> np.ndarray:
    # convert_gaze() from hysts/pytorch_mpiigaze tools/preprocess_mpiigaze.py.
    x, y, z = vector
    return np.array([np.arcsin(-y), np.arctan2(-x, -z)])


def test_normalizing_rotation_properties() -> None:
    normalizer = _make_normalizer(960.0, 0.6, (60, 36))
    image = np.zeros((480, 640, 3), dtype=np.uint8)
    rng = np.random.default_rng(0)
    for _ in range(50):
        center, head_pose_rot = _random_center_and_rotation(rng)
        patch = normalizer.normalize(image, head_pose_rot, center)
        rot_mat = patch.normalizing_rot.as_matrix()
        # Proper rotation matrix.
        np.testing.assert_allclose(rot_mat @ rot_mat.T, np.eye(3), atol=1e-12)
        assert np.linalg.det(rot_mat) > 0
        # The camera looks at the reference point: center maps to the z-axis.
        np.testing.assert_allclose(rot_mat @ (center / np.linalg.norm(center)), [0, 0, 1], atol=1e-12)
        # Roll is canceled: the normalized head x-axis has no y-component.
        normalized_head_x = (rot_mat @ head_pose_rot.as_matrix())[:, 0]
        np.testing.assert_allclose(normalized_head_x[1], 0, atol=1e-12)


def test_normalized_head_pose_matches_mpiigaze_dataset_convention() -> None:
    normalizer = _make_normalizer(960.0, 0.6, (60, 36))
    image = np.zeros((480, 640, 3), dtype=np.uint8)
    rng = np.random.default_rng(1)
    for _ in range(50):
        center, head_pose_rot = _random_center_and_rotation(rng)
        patch = normalizer.normalize(image, head_pose_rot, center)
        expected = _reference_normalized_head_pose(center, head_pose_rot.as_matrix())
        np.testing.assert_allclose(patch.head_rot2d, expected, atol=1e-8)


def test_grayscale_patch_is_single_channel() -> None:
    normalizer = _make_normalizer(960.0, 0.6, (60, 36))
    image = np.zeros((480, 640, 3), dtype=np.uint8)
    center = np.array([0.05, -0.03, 0.55])
    head_pose_rot = Rotation.identity()
    patch = normalizer.normalize(image, head_pose_rot, center, grayscale=True)
    assert patch.image.shape == (36, 60)
    color_patch = normalizer.normalize(image, head_pose_rot, center)
    assert color_patch.image.shape == (36, 60, 3)


def test_gaze_angles_to_vector_matches_dataset_convention() -> None:
    for pitch_deg in range(-40, 50, 10):
        for yaw_deg in range(-40, 50, 10):
            angles = np.radians([pitch_deg, yaw_deg])
            vector = gaze_angles_to_vector(angles)
            np.testing.assert_allclose(np.linalg.norm(vector), 1, atol=1e-12)
            np.testing.assert_allclose(_reference_convert_gaze(vector), angles, atol=1e-12)
            np.testing.assert_allclose(gaze_vector_to_angles(vector), angles, atol=1e-12)


def test_denormalize_gaze_vector_inverts_normalizing_rotation() -> None:
    rng = np.random.default_rng(2)
    for _ in range(20):
        normalizing_rot = Rotation.from_euler("XYZ", rng.uniform(-30, 30, 3), degrees=True)
        gaze_cam = rng.normal(size=3)
        gaze_cam /= np.linalg.norm(gaze_cam)
        gaze_norm = normalizing_rot.as_matrix() @ gaze_cam
        np.testing.assert_allclose(denormalize_gaze_vector(gaze_norm, normalizing_rot), gaze_cam, atol=1e-12)


def test_equivalent_normalized_camera_parameters_produce_identical_warp() -> None:
    # The image warp depends only on the ratio focal / distance of the
    # normalized camera. This is why the packaged parameters (e.g. ETH-XGaze:
    # 960 at 0.6 m, 224 px) are equivalent to the dataset normalization
    # (960 at 0.3 m, 448 px, then downscaled).
    rng = np.random.default_rng(3)
    noise = rng.integers(0, 256, (480, 640, 3), dtype=np.uint8)
    image = cv2.GaussianBlur(noise, (7, 7), 0)
    center = np.array([0.05, -0.03, 0.55])
    head_pose_rot = Rotation.from_euler("XYZ", [10, -15, 5], degrees=True)

    warped = []
    for focal_norm, distance_norm in [(960.0, 0.6), (480.0, 0.3), (1600.0, 1.0)]:
        normalizer = _make_normalizer(focal_norm, distance_norm, (224, 224))
        patch = normalizer.normalize(image, head_pose_rot, center)
        warped.append(patch.image.astype(np.int16))

    for other in warped[1:]:
        assert np.abs(warped[0] - other).max() <= 1
